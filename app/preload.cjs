const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('desktop', {
  start: options => ipcRenderer.invoke('cli:start', options),
  write: data => ipcRenderer.send('cli:write', data),
  resize: (cols, rows) => ipcRenderer.send('cli:resize', cols, rows),
  listProjects: () => ipcRenderer.invoke('project:list'),
  findProjectFiles: query => ipcRenderer.invoke('project:files', query),
  previewProjectFile: file => ipcRenderer.invoke('project:preview', file),
  openProjectEditor: file => ipcRenderer.invoke('project:editor', file),
  stageAttachments: (files, folder) => ipcRenderer.invoke('attachments:stage', files, folder),
  readAttachment: (folder, relativePath, mode) => ipcRenderer.invoke('attachments:read', folder, relativePath, mode),
  revealAttachment: (folder, relativePath) => ipcRenderer.invoke('attachments:reveal', folder, relativePath),
  registerProject: options => ipcRenderer.invoke('project:register', options),
  renameProject: (folder, name) => ipcRenderer.invoke('project:rename', folder, name),
  openProjectFolder: folder => ipcRenderer.invoke('project:open-folder', folder),
  hideProject: folder => ipcRenderer.invoke('project:hide', folder),
  listSessions: folder => ipcRenderer.invoke('session:list', folder),
  listPinnedSessions: () => ipcRenderer.invoke('session:list-pinned'),
  listAllSessions: (query, archived) => ipcRenderer.invoke('session:list-all', query, archived),
  readHistory: (folder, id) => ipcRenderer.invoke('session:read-history', folder, id),
  clearHistory: () => ipcRenderer.send('session:clear-history'),
  updateSession: patch => ipcRenderer.invoke('session:update', patch),
  restoreWorkspace: () => ipcRenderer.invoke('workspace:restore'),
  finishOnboarding: language => ipcRenderer.invoke('settings:finish-onboarding', language),
  restart: () => ipcRenderer.send('window:restart'),
  readDesktopSettings: () => ipcRenderer.invoke('settings:read'),
  desktopVersion: () => ipcRenderer.invoke('desktop:version'),
  saveDesktopSettings: settings => ipcRenderer.invoke('settings:save', settings),
  projectProfile: folder => ipcRenderer.invoke('project:profile', folder),
  saveProjectProfile: (folder, profile) => ipcRenderer.invoke('project:save-profile', folder, profile),
  projectActions: () => ipcRenderer.invoke('actions:list'),
  runProjectAction: (folder, index) => ipcRenderer.invoke('actions:run', folder, index),
  stopProjectAction: id => ipcRenderer.invoke('actions:stop', id),
  onProjectActions: listener => ipcRenderer.on('actions:changed', (_event, value) => listener(value)),
  tasks: (action, input) => ipcRenderer.invoke('tasks:update', action, input),
  readUnreadChats: () => ipcRenderer.invoke('desktop:unread-chats'),
  updateChatAttention: (chats, waiting, badge) => ipcRenderer.send('desktop:chat-attention', { chats, waiting, badge }),
  notify: notice => ipcRenderer.invoke('desktop:notify', notice),
  registerNotificationShortcut: () => ipcRenderer.invoke('desktop:notification-shortcut'),
  onNotificationClick: listener => ipcRenderer.on('desktop:notification-click', (_event, value) => listener(value)),
  onNotificationError: listener => ipcRenderer.on('desktop:notification-error', (_event, value) => listener(value)),
  beginChanges: () => ipcRenderer.invoke('changes:begin'),
  finishChanges: token => ipcRenderer.invoke('changes:finish', token),
  saveTurnDiff: scope => ipcRenderer.invoke('changes:save-turn', scope),
  listTurnDiffs: scope => ipcRenderer.invoke('changes:list-turns', scope),
  readTurnDiff: scope => ipcRenderer.invoke('changes:read-turn', scope),
  workingChanges: () => ipcRenderer.invoke('changes:working'),
  projectBranch: () => ipcRenderer.invoke('project:branch'),
  createWorktree: (folder, base) => ipcRenderer.invoke('project:worktree', folder, base),
  openLocalPreview: url => ipcRenderer.invoke('preview:open', url),
  captureLocalPreview: () => ipcRenderer.invoke('preview:capture'),
  integrationCatalog: folder => ipcRenderer.invoke('project:integrations', folder),
  bindTranscript: (id, includeOtherFolders) => ipcRenderer.send('session:bind-transcript', id, includeOtherFolders),
  onTranscript: listener => ipcRenderer.on('session:transcript', (_event, value) => listener(value)),
  onLive: listener => ipcRenderer.on('session:live', (_event, value) => listener(value)),
  pickFolder: (folder, chooseParent) => ipcRenderer.invoke('project:pick', folder, chooseParent),
  openLink: url => ipcRenderer.send('link:open', url),
  onData: listener => ipcRenderer.on('cli:data', (_event, data) => listener(data)),
  onExit: listener => ipcRenderer.on('cli:exit', (_event, code) => listener(code)),
  onClosing: listener => ipcRenderer.on('window:closing', () => listener()),
  close: idle => ipcRenderer.send(idle ? 'window:quit' : 'window:close-now'),
});
